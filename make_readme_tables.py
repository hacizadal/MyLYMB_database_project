#!/usr/bin/env python3
"""Print the README result tables from a finished sweep folder.

    python make_readme_tables.py results/<sweep_id>

Reads <sweep_id>/alter_results.csv and <sweep_id>/analysis/workload_by_phase.csv
(both written by sweep.sh / analyze_results.py) and prints Markdown to paste into
README section 14.1 and 8.3:

  1. ALTER duration (median over repetitions, seconds) per change x algorithm
  2. Worst concurrent-write latency during the ALTER (median over repetitions of the
     per-run maximum, ms), with the total number of overlapping statements
  3. Workload errors during the ALTER window
  4. A draft Friday table: for each change, the best online algorithm MariaDB accepted

Cells: `refused` = the ALTER failed (error 1846 etc., nothing changed); `-` = no data.
"""
import sys
from pathlib import Path

import pandas as pd

from experiments import ALGORITHMS, CHANGES

ONLINE = ["instant", "nocopy", "inplace", "copy"]   # cheapest first, all LOCK=NONE
SAFE_MS = 1000   # a write held for more than this during the ALTER is "not Friday-safe"


def table(rows, cols, cell):
    out = ["| Change | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for r in rows:
        out.append(f"| {r} | " + " | ".join(cell(r, c) for c in cols) + " |")
    return "\n".join(out)


def main(sweep):
    sweep = Path(sweep)
    alter = pd.read_csv(sweep / "alter_results.csv")
    wl = pd.read_csv(sweep / "analysis" / "workload_by_phase.csv")
    during = wl[wl.phase == "during"]

    changes = [c for c in CHANGES if c in set(alter.change)]
    algos = [a for a in ALGORITHMS if a in set(alter.requested_algorithm)]
    reps = alter.groupby(["change", "requested_algorithm"]).size().max()
    version = alter.server_version.iloc[0]
    rows = int(alter.dataset_rows.iloc[0])

    def runs(c, a):
        return alter[(alter.change == c) & (alter.requested_algorithm == a)]

    def ok(c, a):
        r = runs(c, a)
        return len(r) and (r.status == "success").all()

    def dur(c, a):
        r = runs(c, a)
        if not len(r):
            return "-"
        if not ok(c, a):
            return "refused"
        return f"{r.duration_seconds.median():.2f}"

    def run_ids(c, a):
        return set(runs(c, a).run_id)

    def worst(c, a):
        if not ok(c, a):
            return None
        d = during[during.run_id.isin(run_ids(c, a))]
        if not len(d):
            return None
        per_run_max = d.groupby("run_id").max_ms.max()
        return per_run_max.median(), int(d["count"].sum()), int(d.errors.sum())

    def lat(c, a):
        w = worst(c, a)
        return "-" if w is None else f"{w[0]:.0f} ({w[1]})"

    def err(c, a):
        w = worst(c, a)
        return "-" if w is None else str(w[2])

    print(f"<!-- generated by make_readme_tables.py from {sweep} : MariaDB {version}, "
          f"{rows:,} rows, {reps} repetition(s) -->\n")
    print(f"**ALTER duration, seconds** (median of {reps} run(s); `refused` = MariaDB error, nothing altered)\n")
    print(table(changes, algos, dur))
    print(f"\n**Worst write latency while the ALTER ran, ms** (median over runs of the per-run maximum; "
          "in parentheses: workload statements overlapping the ALTER, all runs)\n")
    print(table(changes, algos, lat))
    print("\n**Workload errors during the ALTER** (lock wait timeouts etc.)\n")
    print(table(changes, algos, err))

    print("\n**Friday table draft** (cheapest online algorithm MariaDB accepted; check the wording by hand)\n")
    print("| Change | Write this | ALTER (s) | Worst write wait (ms) | Friday? |")
    print("|---|---|---|---|---|")
    for c in changes:
        pick = next((a for a in ONLINE if ok(c, a)), None)
        if pick is None:
            print(f"| {c} | no online algorithm accepted | - | - | ❌ plan a maintenance window |")
            continue
        clause = ALGORITHMS[pick][0]
        if CHANGES[c].session:
            clause = "; ".join(CHANGES[c].session) + "; then " + clause
        w = worst(c, pick)
        wait = "-" if w is None else f"{w[0]:.0f}"
        verdict = "✅ yes" if (w is None or (w[0] < SAFE_MS and w[2] == 0)) else "⚠️ check"
        print(f"| {c} | `{clause}` | {dur(c, pick)} | {wait} | {verdict} |")


def headline_figure(sweep):
    """analysis/fig_copy_vs_blocking.png: worst write wait, blocking COPY vs online COPY."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    sweep = Path(sweep)
    alter = pd.read_csv(sweep / "alter_results.csv")
    wl = pd.read_csv(sweep / "analysis" / "workload_by_phase.csv")
    d = wl[(wl.phase == "during") & (wl.alter_status == "success")]
    worst = d.groupby(["change", "algorithm", "run_id"]).max_ms.max().groupby(["change", "algorithm"]).median()
    changes = [c for c in CHANGES if (c, "blocking") in worst and (c, "copy") in worst]
    x = range(len(changes))
    fig, ax = plt.subplots(figsize=(10, 4.2))
    ax.bar([i - 0.2 for i in x], [worst[(c, "blocking")] for c in changes], 0.4,
           label="ALGORITHM=COPY, LOCK=EXCLUSIVE (blocking)", color="#c0504d")
    ax.bar([i + 0.2 for i in x], [worst[(c, "copy")] for c in changes], 0.4,
           label="ALGORITHM=COPY, LOCK=NONE (online, 11.2+)", color="#2e75b6")
    ax.set_yscale("log"); ax.set_ylabel("worst write wait during ALTER (ms, log)")
    ax.set_xticks(list(x)); ax.set_xticklabels(changes, rotation=20, ha="right")
    ax.set_title(f"Same table copy, different lock: {alter.server_version.iloc[0]}, "
                 f"{int(alter.dataset_rows.iloc[0]):,} rows")
    ax.set_ylim(top=ax.get_ylim()[1] * 15)
    ax.legend(loc="upper left", ncol=2, fontsize=9); fig.tight_layout()
    out = sweep / "analysis" / "fig_copy_vs_blocking.png"
    fig.savefig(out, dpi=130)
    print(f"\nfigure written: {out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
    headline_figure(sys.argv[1])
